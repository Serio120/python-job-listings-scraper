"""Render the jobs.csv export as a safe, readable HTML table."""

import csv
from html import escape
from pathlib import Path
from typing import Dict, List, Union
from urllib.parse import urlsplit

CSV_FILE = Path("jobs.csv")
HTML_FILE = Path("jobs.html")


def _safe_http_url(value: str) -> bool:
    """Return True only for absolute HTTP(S) URLs."""
    parsed = urlsplit(value)
    return parsed.scheme in {"http", "https"} and bool(parsed.netloc)


def render_jobs_html(rows: List[Dict[str, str]]) -> str:
    """Render job rows, escaping scraped values before inserting them into HTML."""
    body_rows = []

    for row in rows:
        cells = []
        for field in ("titulo", "empresa", "ubicacion", "url_detalle"):
            value = row.get(field, "N/A")
            safe_value = escape(value)
            if field == "url_detalle" and _safe_http_url(value):
                cells.append(
                    '<td><a href="{}" target="_blank" '
                    'rel="noopener noreferrer">{}</a></td>'.format(safe_value, safe_value)
                )
            else:
                cells.append("<td>{}</td>".format(safe_value))
        body_rows.append("<tr>" + "".join(cells) + "</tr>")

    return """<!DOCTYPE html>
<html lang="es">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Ofertas de empleo</title>
  <style>
    body { font-family: system-ui, sans-serif; margin: 2rem; }
    table { border-collapse: collapse; width: 100%; }
    th, td { border: 1px solid #ccc; padding: 0.65rem; text-align: left; }
    th { background: #f2f2f2; }
    tr:nth-child(even) { background: #fafafa; }
    a { overflow-wrap: anywhere; }
  </style>
</head>
<body>
  <h1>Ofertas de empleo</h1>
  <table>
    <thead><tr><th>Título</th><th>Empresa</th><th>Ubicación</th><th>URL</th></tr></thead>
    <tbody>
""" + "\n".join(body_rows) + """
    </tbody>
  </table>
</body>
</html>
"""


def read_jobs_csv(csv_path: Union[Path, str] = CSV_FILE) -> List[Dict[str, str]]:
    """Read job rows from the CSV file generated by scraper.py."""
    with Path(csv_path).open(newline="", encoding="utf-8") as csv_file:
        return list(csv.DictReader(csv_file))


def main() -> None:
    rows = read_jobs_csv()
    HTML_FILE.write_text(render_jobs_html(rows), encoding="utf-8")
    print("HTML report generated: {}".format(HTML_FILE))


if __name__ == "__main__":
    main()
